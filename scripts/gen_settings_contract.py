"""
Generate the frontend settings contract from the canonical backend schema.

The JSON Schema in ``previewgen/settings_schema.json`` is the single source of
truth. This script projects it into a TypeScript module
(``frontend/src/generated/settingsContract.ts``) so the frontend defaults and
validation metadata cannot silently drift from the backend.

Run:  python scripts/gen_settings_contract.py
"""
from __future__ import annotations

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCHEMA_PATH = REPO_ROOT / "previewgen" / "settings_schema.json"
OUTPUT_PATH = REPO_ROOT / "frontend" / "src" / "generated" / "settingsContract.ts"

HEADER = (
    "// AUTO-GENERATED by scripts/gen_settings_contract.py -- DO NOT EDIT BY HAND.\n"
    "// Source of truth: previewgen/settings_schema.json\n"
)


def build_contract(schema: dict) -> str:
    properties: dict = schema.get("properties", {})
    version = properties.get("schemaVersion", {}).get("const", 1)

    defaults: dict = {}
    fields: list[dict] = []
    for name, prop in properties.items():
        if name == "schemaVersion":
            continue
        if "default" in prop:
            defaults[name] = prop["default"]

        field: dict = {"name": name, "type": prop.get("type", "string")}
        for key, out_key in (
            ("enum", "enum"),
            ("pattern", "pattern"),
            ("minimum", "minimum"),
            ("maximum", "maximum"),
            ("maxLength", "maxLength"),
        ):
            if key in prop:
                field[out_key] = prop[key]
        fields.append(field)

    defaults_json = json.dumps(defaults, indent=2)
    fields_json = json.dumps(fields, indent=2)

    return (
        HEADER
        + "\n"
        + f"export const SETTINGS_SCHEMA_VERSION = {version};\n\n"
        + "export const SETTINGS_DEFAULTS = "
        + defaults_json
        + " as const;\n\n"
        + "export interface SettingsField {\n"
        + "  name: string;\n"
        + "  type: string;\n"
        + "  enum?: readonly string[];\n"
        + "  pattern?: string;\n"
        + "  minimum?: number;\n"
        + "  maximum?: number;\n"
        + "  maxLength?: number;\n"
        + "}\n\n"
        + "export const SETTINGS_FIELDS: readonly SettingsField[] = "
        + fields_json
        + " as const;\n"
    )


def generate(output_path: Path = OUTPUT_PATH, schema_path: Path = SCHEMA_PATH) -> str:
    schema = json.loads(schema_path.read_text(encoding="utf-8"))
    content = build_contract(schema)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(content, encoding="utf-8")
    return content


if __name__ == "__main__":
    generate()
    print(f"Wrote {OUTPUT_PATH}")
